"""
Unit tests for agent tools (search_knowledge_base, query_structured_data, generate_report).
"""

from unittest.mock import MagicMock, patch
from sqlalchemy.orm import Session

from app.tools.search_kb_tool import search_knowledge_base
from app.tools.db_query_tool import query_structured_data, ALLOWED_QUERY_TYPES
from app.tools.report_tool import generate_report


@patch("app.tools.search_kb_tool.retrieval_service.retrieve_context")
def test_search_knowledge_base_tool(mock_retrieve):
    mock_retrieve.return_value = [
        {"id": "c1", "document_id": "d1", "text": "DocuMind tools support function calling."},
    ]
    results = search_knowledge_base(query="tools", user_id="user-123", k=2)

    assert len(results) == 1
    assert results[0]["chunk_id"] == "c1"
    assert results[0]["document_id"] == "d1"
    assert "DocuMind tools" in results[0]["text"]
    mock_retrieve.assert_called_once_with(query="tools", user_id="user-123", k=2)


def test_db_query_tool_rejects_unwhitelisted_query():
    """Confirms arbitrary SQL or non-whitelisted query types are rejected."""
    mock_db = MagicMock(spec=Session)
    res = query_structured_data(
        query_type="SELECT * FROM users; DROP TABLE chunks;",
        user_id="user-123",
        db=mock_db,
    )
    assert "error" in res
    assert "Invalid query_type" in res["error"]
    assert not mock_db.query.called


def test_db_query_tool_document_summary():
    mock_db = MagicMock(spec=Session)
    # mock total docs
    mock_db.query.return_value.filter.return_value.scalar.return_value = 5
    # mock join query for chunks
    mock_db.query.return_value.join.return_value.filter.return_value.scalar.return_value = 25
    # mock status group by
    mock_db.query.return_value.filter.return_value.group_by.return_value.all.return_value = [
        ("ready", 4),
        ("processing", 1),
    ]

    res = query_structured_data(
        query_type="document_summary",
        user_id="user-123",
        db=mock_db,
    )
    assert res["query_type"] == "document_summary"
    assert "total_documents" in res
    assert "status_breakdown" in res


def test_db_query_tool_recent_documents():
    mock_db = MagicMock(spec=Session)
    doc_mock = MagicMock()
    doc_mock.id = "doc-1"
    doc_mock.filename = "report.pdf"
    doc_mock.status = "ready"
    doc_mock.created_at = None

    mock_db.query.return_value.filter.return_value.order_by.return_value.limit.return_value.all.return_value = [doc_mock]
    mock_db.query.return_value.filter.return_value.scalar.return_value = 3

    res = query_structured_data(
        query_type="recent_documents",
        user_id="user-123",
        db=mock_db,
        limit=5,
    )
    assert res["query_type"] == "recent_documents"
    assert res["count"] == 1
    assert res["documents"][0]["filename"] == "report.pdf"


def test_generate_report_tool():
    report = generate_report(
        title="Q3 Security Audit",
        summary="All systems are operating securely with no critical vulnerabilities.",
        sections=[
            {"heading": "Network Security", "content": "Firewalls and TLS configs verified."},
            {"heading": "Access Control", "content": "RBAC and tenant scoping enforced."},
        ],
    )
    markdown = report["markdown_report"]
    assert "# Q3 Security Audit" in markdown
    assert "## Executive Summary" in markdown
    assert "## Network Security" in markdown
    assert "## Access Control" in markdown
    assert "*Report generated by DocuMind Intelligence Agent.*" in markdown
