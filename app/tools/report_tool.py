"""
Agent Tool: generate_report

Formats retrieved evidence, metadata, and synthesis into a structured Markdown report.
"""

from __future__ import annotations

from typing import Any


def generate_report(
    title: str,
    summary: str,
    sections: list[dict[str, str]],
    **kwargs: Any,
) -> dict[str, str]:
    """
    Generate a well-structured markdown report.

    Parameters
    ----------
    title:
        Report title.
    summary:
        Executive summary or main conclusion.
    sections:
        List of dicts each with 'heading' and 'content' keys.

    Returns
    -------
    dict with 'markdown_report' string.
    """
    lines = [
        f"# {title.strip()}",
        "",
        "## Executive Summary",
        summary.strip(),
        "",
    ]

    for sec in sections:
        heading = sec.get("heading", "Section").strip()
        content = sec.get("content", "").strip()
        lines.append(f"## {heading}")
        lines.append(content)
        lines.append("")

    lines.append("---")
    lines.append("*Report generated by DocuMind Intelligence Agent.*")

    return {"markdown_report": "\n".join(lines)}
